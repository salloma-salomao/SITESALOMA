document.querySelectorAll(".gallery").forEach(gallery => {
  const id = gallery.dataset.gallery;
  const images = galleries[id];
  let index = 0;

  const imgElement = gallery.querySelector("img");

  function loadImage(i) {
    const img = new Image();
    img.src = images[i];

    img.onload = () => {
      imgElement.src = img.src;
    };
  }

  // carregar primeira imagem
  loadImage(index);

  gallery.querySelector(".next").addEventListener("click", () => {
    index = (index + 1) % images.length;
    loadImage(index);
  });

  gallery.querySelector(".prev").addEventListener("click", () => {
    index = (index - 1 + images.length) % images.length;
    loadImage(index);
  });
});

// Função para scroll suave para contato
function scrollToContact() {
    const contactSection = document.getElementById('contato');
    if (contactSection) {
        contactSection.scrollIntoView({
            behavior: 'smooth',
            block: 'start'
        });
    }
}

const lightbox = document.getElementById("lightbox");
const lightboxImg = lightbox.querySelector("img");

// abrir ao clicar na imagem da galeria
document.querySelectorAll(".gallery img").forEach(img => {
  img.addEventListener("click", () => {
    lightboxImg.src = img.src;
    lightbox.classList.remove("hidden");
  });
});

// fechar ao clicar em qualquer lugar
lightbox.addEventListener("click", () => {
  lightbox.classList.add("hidden");
  lightboxImg.src = "";
});